CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    category VARCHAR(100),
    level VARCHAR(30),
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    teacher_id BIGINT NOT NULL,
    price NUMERIC(10,2),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

CREATE TABLE lessons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    content TEXT,
    position INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT fk_lessons_course FOREIGN KEY (course_id) REFERENCES courses (id)
);

CREATE TABLE resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT,
    lesson_id BIGINT,
    name VARCHAR(200) NOT NULL,
    type VARCHAR(30) NOT NULL,
    url VARCHAR(500) NOT NULL,
    size VARCHAR(50),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_resources_course FOREIGN KEY (course_id) REFERENCES courses (id),
    CONSTRAINT fk_resources_lesson FOREIGN KEY (lesson_id) REFERENCES lessons (id),
    CONSTRAINT chk_resource_owner CHECK (course_id IS NOT NULL OR lesson_id IS NOT NULL)
);

CREATE INDEX idx_courses_teacher_id ON courses (teacher_id);
CREATE INDEX idx_lessons_course_id ON lessons (course_id);
CREATE INDEX idx_resources_course_id ON resources (course_id);
CREATE INDEX idx_resources_lesson_id ON resources (lesson_id);
